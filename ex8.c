#include <stdio.h>
#include <math.h>

int main(void) {
  int N ;
  double r=0.5, l, xo, yo ;
  scanf("%d" , &N);

  for (int i = 0; i < N; i++)
    {
     scanf("%lf" , &l);
     if (l<2)
       {
       xo = (l+r) * cos ((2*M_PI*i)/N);
       yo = (l+r) * sin ((2*M_PI*i)/N);

       printf("%.1lf %.1lf\n" , xo, yo);
       }
    }

    return 0;
}

